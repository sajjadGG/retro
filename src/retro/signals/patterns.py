# --- injected (non-human) user turns -----------------------------------------

INJECTED_MARKERS: tuple[str, ...] = (
    "<command-name>",
    "<command-message>",
    "<command-args>",
    "<local-command-stdout>",
    "<local-command-stderr>",
    "<local-command-caveat>",
    "<system-reminder>",
    "<environment_context>",
    "<user_instructions>",
    "<editor_context>",
    "<attachment",
    "<ide_selection>",
    "<ide_opened_file>",
    "caveat: the messages below were generated by the user while running local commands",
    "this session is being continued from a previous conversation",
    "[request interrupted by user",
    "api error:",
    "tool_use_id",
)

# Tags the host wraps around injected context. Their paired form is stripped so a
# message that mixes injected context with a real request keeps the request.
_INJECTED_TAGS = (
    "command-name", "command-message", "command-args", "local-command-stdout",
    "local-command-stderr", "local-command-caveat", "system-reminder",
    "environment_context", "user_instructions", "editor_context", "task-notification",
    "subagent_notification", "turn_aborted", "recommended_plugins", "skill-context",
    "user-prompt-submit-hook", "ide_selection", "ide_opened_file",
)
_INJECTED_BLOCK_RE = re.compile(
    r"<(" + "|".join(_INJECTED_TAGS) + r")(?:\s[^>]*)?>.*?</\1>",
    re.DOTALL | re.IGNORECASE,
)

# A user turn that *starts* with one of these is injected context, not a human
# turn, even when the host never closes the tag.
INJECTED_PREFIXES: tuple[str, ...] = tuple(
    f"<{tag}" for tag in _INJECTED_TAGS
) + (
    "<attachment",
    "# agents.md instructions for",
    "caveat: the messages below were generated by the user while running local commands",
    "this session is being continued from a previous conversation",
    "[request interrupted by user",
    "api error:",
)
_SELF_CLOSING_RE = re.compile(r"<[a-z_-]+\s*/>", re.IGNORECASE)


def human_text(text: str) -> str:
    """Strip injected blocks; what remains is what the human actually typed."""
    if not text:
        return ""
    stripped = _INJECTED_BLOCK_RE.sub(" ", text)
    stripped = _SELF_CLOSING_RE.sub(" ", stripped)
    return stripped.strip()


def is_injected_user_text(text: str, payload: Mapping[str, Any]) -> bool:
    if payload.get("isMeta") is True or payload.get("synthetic") is True:
        return True
    if payload.get("is_meta") is True:
        return True
    content = payload.get("content")
    if isinstance(content, list) and content:
        kinds = {
            item.get("type")
            for item in content
            if isinstance(item, dict) and isinstance(item.get("type"), str)
        }
        if kinds and kinds <= {"tool_result", "image", "document"}:
            return True
    lowered = (text or "").strip().lower()
    if not lowered:
        return True
    remainder = human_text(text)
    if lowered.startswith(INJECTED_PREFIXES):
        stripped = remainder.strip().lower()
        return not stripped or stripped.startswith(INJECTED_PREFIXES)
    for marker in INJECTED_MARKERS:
        if marker in lowered[:400]:
            return not remainder
    return False


# --- user corrections --------------------------------------------------------

# Split by how safely the pattern distinguishes a reaction from a fresh
# instruction. "do not modify any files" is a normal task brief, not a
# correction, so the weak set only counts inside a short reply.
STRONG_CORRECTION_PATTERNS: tuple[str, ...] = (
    r"^\s*(?:no|nope|nah)\b(?!\s+(?:need|problem|worries|rush|changes?|more|longer|idea|issue))",
    r"^\s*(?:wrong|stop|revert|undo|rollback)\b",
    r"\bthat'?s\s+(?:wrong|incorrect|not\s+right|not\s+what|not\s+it|not\s+the)\b",
    r"\bnot\s+what\s+i\s+(?:asked|wanted|meant|said)\b",
    r"\bi\s+(?:said|told\s+you|already\s+told\s+you|asked\s+for)\b",
    r"\byou\s+(?:broke|removed|deleted|ignored|missed|misunderstood|reverted|forgot)\b",
    r"\bstill\s+(?:broken|failing|fails|wrong|not\s+working|doesn'?t\s+work)\b",
    r"\b(?:revert|undo|roll\s*back)\s+(?:that|this|it|your|the\s+last|everything)\b",
    r"\bwhy\s+did\s+you\s+(?:remove|delete|change|add|break|do)\b",
    r"\b(?:doesn'?t|does\s+not)\s+work\b",
    r"\bgo\s+back\s+to\b",
    r"\bre-?read\s+(?:the|my)\b",
    r"\bdon'?t\s+(?:do|change|touch|edit|delete|remove)\s+(?:that|this|it|those|them)\b",
    r"^\s*(?:actually|wait|hold\s+on)\b",
    r"\b(?:operational\s+)?correction\b\s*[:,-]",
    r"\bi\s+(?:don'?t|do\s+not)\s+see\b",
    r"\byou\s+(?:were|are)\s+(?:supposed|meant)\s+to\b",
    r"\bwrong\s+(?:file|place|branch|answer|approach|direction|one)\b",
    r"\bthat\s+is\s+not\s+(?:what|right|correct)\b",
)
WEAK_CORRECTION_PATTERNS: tuple[str, ...] = (
    r"\b(?:don'?t|do\s+not|never)\s+(?:do|use|add|remove|delete|change|run|touch|modify|create|edit)\b",
    r"\bstop\s+(?:doing|using|changing|editing|running|adding)\b",
    r"\binstead\s+of\s+\S+.{0,40}\buse\b",
)
CORRECTION_PATTERNS = STRONG_CORRECTION_PATTERNS + WEAK_CORRECTION_PATTERNS
STRONG_CORRECTION_RE = re.compile("|".join(f"(?:{p})" for p in STRONG_CORRECTION_PATTERNS), re.IGNORECASE)
WEAK_CORRECTION_RE = re.compile("|".join(f"(?:{p})" for p in WEAK_CORRECTION_PATTERNS), re.IGNORECASE)
WEAK_CORRECTION_MAX_CHARS = 180
WEAK_CORRECTION_HEAD_CHARS = 120


def is_correction(text: str) -> bool:
    """True when a human turn rejects or reverses what the agent just did."""
    head = (text or "")[:400]
    if STRONG_CORRECTION_RE.search(head):
        return True
    if len(text or "") > WEAK_CORRECTION_MAX_CHARS:
        return False
    # A brief lists several prohibitions ("do not modify, do not create, ...");
    # a correction objects to exactly one thing.
    return len(WEAK_CORRECTION_RE.findall(head[:WEAK_CORRECTION_HEAD_CHARS])) == 1


