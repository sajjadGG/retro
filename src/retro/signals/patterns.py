_SECRET_SPECS: Sequence[tuple[str, str]] = (
    ("openai_api_key", r"\bsk-(?:proj-)?[A-Za-z0-9_-]{32,}\b"),
    ("anthropic_api_key", r"\bsk-ant-[A-Za-z0-9_-]{32,}\b"),
    ("github_token", r"\bgh[opsru]_[A-Za-z0-9_]{32,}\b"),
    ("github_pat", r"\bgithub_pat_[A-Za-z0-9_]{40,}\b"),
    ("aws_access_key_id", r"\b(?:AKIA|ASIA)[A-Z0-9]{16}\b"),
    ("google_api_key", r"\bAIza[0-9A-Za-z_-]{35}\b"),
    ("stripe_secret_key", r"\bsk_(?:live|test)_[0-9A-Za-z]{24,}\b"),
    ("slack_token", r"\bxox[baprs]-[A-Za-z0-9-]{20,}\b"),
    ("private_key_block", r"-----BEGIN (?:RSA |EC |OPENSSH |PGP )?PRIVATE KEY-----"),
    ("jwt", r"\beyJ[A-Za-z0-9_-]{16,}\.[A-Za-z0-9_-]{16,}\.[A-Za-z0-9_-]{16,}\b"),
    (
        "secret_assignment",
        r"(?i:\b(?:api[_-]?key|secret[_-]?key|access[_-]?token|auth[_-]?token|client[_-]?secret|password)"
        r"\s*[:=]\s*[\"']?(?P<secret_value>[A-Za-z0-9_\-/+=.]{20,})[\"']?)",
    ),
)
SECRET_RE = re.compile("|".join(f"(?P<{name}>{pattern})" for name, pattern in _SECRET_SPECS))
_PLACEHOLDER_RE = re.compile(
    r"(?i)^(?:x{4,}|\*{4,}|\.{3,}|<.*>|\$\{?[a-z_]+\}?|your[-_].*|my[-_].*|example.*|"
    r"placeholder.*|redacted.*|dummy.*|test[-_]?(?:key|token|secret).*|changeme.*|"
    r"none|null|undefined|true|false|abc123.*|[0-9a-f]{40}|sha256:.*)$"
)
_ENV_REFERENCE_RE = re.compile(
    r"(?i)(process\.env|os\.environ|getenv|ENV\[|secrets\.|vault|\$\{|\$[A-Z_]{3,})"
)

SECRET_SCAN_EVENT_LIMIT = 100_000
SECRET_SCAN_SESSION_LIMIT = 8_000_000


def find_secrets(text: str) -> Iterator[str]:
    """Yield secret kind names found in *text*, filtering obvious placeholders."""
    for match in SECRET_RE.finditer(text):
        kind = match.lastgroup
        if kind == "secret_value":
            kind = "secret_assignment"
        if kind is None:
            continue
        if kind == "secret_assignment":
            value = match.groupdict().get("secret_value") or ""
            window = text[max(0, match.start() - 60) : match.end() + 20]
            if _PLACEHOLDER_RE.match(value) or _ENV_REFERENCE_RE.search(window):
                continue
            if value.count("-") >= 4 and len(value) <= 40:
                continue
        yield kind


