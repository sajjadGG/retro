"""Lexicons and regexes used by the profile builder.

Every pattern here is tuned for precision over recall: a false "the user
corrected the agent" or "a secret leaked" is far more damaging to the metrics
than a miss, because these feed rates the user is supposed to act on.
"""

from __future__ import annotations

