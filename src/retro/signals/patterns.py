def iter_payload_strings(value: Any, *, budget: int = SECRET_SCAN_EVENT_LIMIT) -> Iterator[str]:
    """Yield string leaves of a payload without materializing JSON."""
    stack = [value]
    spent = 0
    while stack:
        current = stack.pop()
        if isinstance(current, str):
            if not current:
                continue
            spent += len(current)
            yield current if spent <= budget else current[: max(0, budget - spent + len(current))]
            if spent >= budget:
                return
        elif isinstance(current, dict):
            for key, child in current.items():
                if isinstance(key, str):
                    spent += len(key)
                    yield key
                stack.append(child)
        elif isinstance(current, list):
            stack.extend(current)
